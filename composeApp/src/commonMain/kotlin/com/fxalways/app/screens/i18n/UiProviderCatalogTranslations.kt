internal fun localizedProviderCatalogText(language: String, text: String): String? {
    val normalized = language.lowercase().substringBefore("-").substringBefore("_")
    val direct = providerCatalogTranslations[normalized]?.get(text)
    if (direct != null) return direct

    return providerCatalogTranslations["en"]?.get(text)
        ?: providerCatalogTranslations["es"]?.get(text)
}
